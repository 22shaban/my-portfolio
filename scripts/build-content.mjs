/**
 * Regenerates `content/projects.generated.ts` from the JSON files in
 * `content/projects/`. The CMS writes those JSON files, so nothing else in
 * the codebase has to change when a project is added, removed or reordered.
 *
 * Runs automatically before `npm run dev` and `npm run build`.
 * Manual run: `npm run content`
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const dir = path.join(root, "content", "projects");
const outFile = path.join(root, "content", "projects.generated.ts");

const files = (await readdir(dir))
  .filter((file) => file.endsWith(".json"))
  .sort();

const entries = [];

for (const file of files) {
  const raw = await readFile(path.join(dir, file), "utf8");
  let data;
  try {
    data = JSON.parse(raw);
  } catch (error) {
    throw new Error(
      `content/projects/${file} is not valid JSON: ${error.message}`,
    );
  }
  if (!data.slug || !data.title) {
    throw new Error(`content/projects/${file} needs at least "slug" and "title"`);
  }
  entries.push({ file, data });
}

// `order` decides the position in the work index; ties fall back to title.
entries.sort(
  (a, b) =>
    (Number(a.data.order) || 999) - (Number(b.data.order) || 999) ||
    String(a.data.title).localeCompare(String(b.data.title)),
);

const imports = entries
  .map((entry, i) => `import p${i} from "./projects/${entry.file}";`)
  .join("\n");

const list = entries.map((_, i) => `  p${i},`).join("\n");

const output = `/* AUTO-GENERATED by scripts/build-content.mjs — do not edit by hand. */
${imports}

export const projectEntries = [
${list}
];
`;

await writeFile(outFile, output, "utf8");
console.log(`content: ${entries.length} project(s) -> content/projects.generated.ts`);
